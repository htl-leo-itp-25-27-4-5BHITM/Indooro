#!/usr/bin/env node
// Generates TypeScript types from the reviewed shared contract into every consumer location.
// Usage: node scripts/contract/generate-types.mjs [--check]
// --check regenerates in memory and exits 1 when a target is missing or differs (generated-file freshness).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const REVIEWED = resolve(repoRoot, "openspec/specs/shared-api/openapi.yaml");
const TARGETS = [
  "admin-ui/src/api/generated/schema.d.ts",
  "backend/indooro_server/src/main/resources/META-INF/resources/admin/types/api.d.ts",
  "backend/indooro_server/src/main/resources/META-INF/resources/customer/types/api.d.ts",
].map(path => resolve(repoRoot, path));
const BANNER = "// Generated by scripts/contract/generate-types.mjs from openspec/specs/shared-api/openapi.yaml. Do not edit.\n";

export async function renderTypes() {
  const ast = await openapiTS(pathToFileURL(REVIEWED));
  return BANNER + astToString(ast);
}

async function main(argv) {
  const text = await renderTypes();
  if (argv.includes("--check")) {
    let stale = 0;
    for (const target of TARGETS) {
      const onDisk = existsSync(target) ? readFileSync(target, "utf8") : null;
      if (onDisk !== text) {
        stale++;
        console.error(`STALE: ${target} ${onDisk === null ? "is missing" : "differs"}; run npm run contract:types`);
      }
    }
    if (stale === 0) console.log(`OK: ${TARGETS.length} generated type files are up to date`);
    return stale === 0 ? 0 : 1;
  }
  for (const target of TARGETS) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
    console.log(`wrote ${target}`);
  }
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exitCode = await main(process.argv.slice(2));
}
