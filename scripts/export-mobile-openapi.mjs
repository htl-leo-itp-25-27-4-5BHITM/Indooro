#!/usr/bin/env node
// Writes api/openapi/indooro-mobile.yaml: the reviewed shared contract filtered to operations whose
// x-indooro-consumers include "ios", with unreferenced components pruned and x-indooro-* keys removed
// from operations. Usage: node scripts/export-mobile-openapi.mjs [--check]
// --check regenerates in memory and exits 1 when the file on disk is missing or differs.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";
import { parse, stringify } from "yaml";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const REVIEWED = resolve(repoRoot, "openspec/specs/shared-api/openapi.yaml");
export const OUTPUT = resolve(repoRoot, "api/openapi/indooro-mobile.yaml");
const HEADER = "# Generated by scripts/export-mobile-openapi.mjs from openspec/specs/shared-api/openapi.yaml. Do not edit.\n";
const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];
const COMPONENT_KINDS = ["schemas", "responses", "parameters"];

function collectRefs(node, refs) {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item, refs);
  } else if (node && typeof node === "object") {
    if (typeof node.$ref === "string" && node.$ref.startsWith("#/components/")) refs.add(node.$ref);
    for (const value of Object.values(node)) collectRefs(value, refs);
  }
}

function securityNames(node, names) {
  for (const requirement of node?.security ?? []) for (const name of Object.keys(requirement)) names.add(name);
}

export function buildMobileDocument(reviewed) {
  const paths = {};
  const usedTags = new Set();
  const usedSecurity = new Set();
  for (const [path, item] of Object.entries(reviewed.paths ?? {})) {
    const kept = {};
    for (const [method, op] of Object.entries(item)) {
      if (!METHODS.includes(method) || !(op["x-indooro-consumers"] ?? []).includes("ios")) continue;
      const clean = Object.fromEntries(Object.entries(op).filter(([key]) => !key.startsWith("x-indooro-")));
      kept[method] = clean;
      (op.tags ?? []).forEach(tag => usedTags.add(tag));
      securityNames(op, usedSecurity);
    }
    if (Object.keys(kept).length === 0) continue;
    paths[path] = { ...(item.parameters ? { parameters: item.parameters } : {}), ...kept };
  }
  securityNames(reviewed, usedSecurity);

  const refs = new Set();
  collectRefs(paths, refs);
  const closure = new Set();
  const queue = [...refs];
  while (queue.length > 0) {
    const ref = queue.pop();
    if (closure.has(ref)) continue;
    closure.add(ref);
    const [, , kind, name] = ref.split("/");
    const target = reviewed.components?.[kind]?.[name];
    const nested = new Set();
    collectRefs(target, nested);
    queue.push(...nested);
  }

  const components = {};
  for (const kind of COMPONENT_KINDS) {
    const source = reviewed.components?.[kind] ?? {};
    const kept = Object.fromEntries(Object.keys(source)
      .filter(name => closure.has(`#/components/${kind}/${name}`))
      .map(name => [name, source[name]]));
    if (Object.keys(kept).length > 0) components[kind] = kept;
  }
  const schemes = Object.fromEntries(Object.entries(reviewed.components?.securitySchemes ?? {})
    .filter(([name]) => usedSecurity.has(name)));
  if (Object.keys(schemes).length > 0) components.securitySchemes = schemes;

  const doc = {};
  for (const key of ["openapi", "info", "servers"]) if (reviewed[key] !== undefined) doc[key] = reviewed[key];
  if (reviewed.tags) doc.tags = reviewed.tags.filter(tag => usedTags.has(tag.name));
  doc.security = reviewed.security ?? [];
  doc.paths = paths;
  doc.components = components;
  return doc;
}

export function renderMobile(reviewed) {
  return HEADER + stringify(buildMobileDocument(reviewed), { lineWidth: 0 });
}

function main(argv) {
  const reviewed = parse(readFileSync(REVIEWED, "utf8"));
  const text = renderMobile(reviewed);
  if (argv.includes("--check")) {
    const onDisk = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : null;
    if (onDisk === text) {
      console.log("OK: api/openapi/indooro-mobile.yaml is up to date");
      return 0;
    }
    console.error(onDisk === null
      ? "STALE: api/openapi/indooro-mobile.yaml is missing; run npm run contract:mobile"
      : "STALE: api/openapi/indooro-mobile.yaml differs from the reviewed contract; run npm run contract:mobile");
    return 1;
  }
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exitCode = main(process.argv.slice(2));
}
