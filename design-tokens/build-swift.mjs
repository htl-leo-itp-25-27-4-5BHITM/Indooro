// Swift consumes resolved DTCG values, never the serialized CSS representation.
export function buildSwift(entries, resolve) {
  const groups = { Color: [], Spacing: [], Radius: [] };
  const names = new Set();
  for (const [key, token] of entries) {
    const value = resolve(token.$value, [key]);
    const [root, ...parts] = key.split('.');
    let group;
    let literal;
    if (root === 'color' && token.$type === 'color') {
      group = 'Color';
      literal = `SwiftUI.Color(.sRGB, red: ${value.components[0]}, green: ${value.components[1]}, blue: ${value.components[2]}, opacity: ${value.alpha})`;
    } else if (['space', 'radius'].includes(root) && token.$type === 'dimension' && value.unit === 'px') {
      group = root === 'space' ? 'Spacing' : 'Radius';
      literal = `CGFloat(${value.value})`;
    } else continue;
    let name = parts.join('-').replace(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase());
    if (/^[0-9]/.test(name)) name = `value${name}`;
    const qualified = `${group}.${name}`;
    if (names.has(qualified)) throw new Error(`Swift name collision: ${key}`);
    names.add(qualified);
    groups[group].push(`        /// ${key}\n        static let ${name} = ${literal}`);
  }
  return `// Generated by design-tokens/build.mjs. Do not edit.
import SwiftUI

// px dimensions map one-to-one to SwiftUI points. Browser-relative rem values
// are intentionally omitted because iOS has no equivalent root font size.
enum IndooroTokens {
${Object.entries(groups).map(([name, lines]) => `    enum ${name} {\n${lines.join('\n')}\n    }`).join('\n\n')}
}
`;
}
